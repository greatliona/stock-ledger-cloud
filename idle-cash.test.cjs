const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(__dirname + '/app.js', 'utf8');
function fn(name) {
  const start = source.indexOf('function ' + name + '(');
  const end = source.indexOf('\nfunction ', start + 1);
  return source.slice(start, end < 0 ? undefined : end);
}
const state = {holdings:[], usHoldings:[], funds:[], cryptoContracts:[], cash:1000, usCashUsd:0, cryptoCashUsdt:100, usdTwdRate:32};
const ctx = {state, toNumber:v=>Number(v)||0, calculateCryptoPosition:v=>v};
vm.createContext(ctx);
vm.runInContext(fn('getPortfolioTotals'), ctx);
let totals = vm.runInContext('getPortfolioTotals()', ctx);
assert.equal(totals.value, 4200);
assert.equal(totals.cash, 1000);
assert.equal(totals.cryptoTotal, 3200);
assert.equal(totals.pnl, 0);
state.cryptoContracts.push({currentValueTwd:2000,costTwd:1500});
totals = vm.runInContext('getPortfolioTotals()', ctx);
assert.equal(totals.value, 6200);
assert.equal(totals.cryptoPnl, 500);
assert.equal(totals.cryptoPnlPct, 500 / 1500 * 100);
delete state.cryptoCashUsdt;
assert.equal(vm.runInContext('getPortfolioTotals().value', ctx), 3000);
assert(fn('drawCryptoPieChart').includes('slices.unshift({label: "USDT"'));
assert(!fn('drawCategoryPieChart').includes('idleUsdtValue'));
assert(fn('migrateState').includes('cryptoCashUsdt: Math.max(0, toNumber(value.cryptoCashUsdt))'));
console.log('PASS: USDT belongs to crypto once, excluded from profit, legacy data defaults to zero');
const migration = vm.createContext({crypto:require('node:crypto').webcrypto});
vm.runInContext('const LEGACY_PURCHASE_DATE="2026-09-05";\n' + source.match(/^function \w+\([^]*?^}/gm).join('\n'), migration);
const saved = {holdings:[],history:[{date:'2026-11-07',cash:1000,cashRecorded:true,cryptoTotal:5200,cryptoCost:1500,cryptoCashUsdt:100,cryptoCashTwd:3200}], cash:1000,cryptoCashUsdt:100,usdTwdRate:32};
const restored = migration.migrateState(JSON.parse(JSON.stringify(saved)));
assert.equal(restored.cryptoCashUsdt,100);
assert.equal(restored.history[0].total,6200);
assert.equal(restored.history[0].pnl,500);
assert.equal(restored.history[0].cryptoCashTwd,3200);
assert.equal(migration.migrateState({holdings:[],history:[],cash:1000}).cryptoCashUsdt,0);
console.log('PASS: backup roundtrip and history preserve USDT without inflating profit');
