const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/app.js','utf8');
const now=new Date('2026-11-23T02:00:00Z');
const state={holdings:[],usHoldings:[],funds:[],cryptoContracts:[],history:[],dailyPriceHistory:[{date:'2026-11-22',prices:{}}],usdTwdRate:32,usCashUsd:99999,cryptoCashUsdt:99999};
const nodes=['tw','us','fund','crypto','all'].map(market=>({dataset:{categoryDaily:market}}));
const ctx=vm.createContext({state,document:{querySelectorAll:selector=>selector==='[data-category-daily]'?nodes:[]}});
vm.runInContext(source.match(/^function \w+\([^]*?^}/gm).join('\n'),ctx);
function add(market,item,previous) {
  ({tw:state.holdings,us:state.usHoldings,fund:state.funds,crypto:state.cryptoContracts}[market]).push(item);
  if(previous) state.dailyPriceHistory[0].prices[ctx.dailyPriceKey(market,item)]=previous;
}
add('tw',{id:'a',symbol:'A',shares:10,currentPrice:110},{price:100});
add('tw',{id:'b',symbol:'B',shares:1,currentPrice:80},{price:100});
let change=ctx.getCategoryDailyChange('tw',now);
assert.equal(change.amount,80);
assert.equal(change.basis,1100);
assert.ok(Math.abs(change.pct-80/1100*100)<1e-10,'weighted return, not arithmetic mean of 10% and -20%');
assert.equal(change.partial,false);
add('tw',{id:'s',symbol:'S',side:'short',shares:5,currentPrice:90},{price:100});
assert.equal(ctx.getCategoryDailyChange('tw',now).amount,130);
state.holdings[0].shares=5;
assert.equal(ctx.getCategoryDailyChange('tw',now).amount,80,'current quantities do not turn sales into daily losses');
add('tw',{id:'missing',symbol:'M',shares:1,currentPrice:100});
change=ctx.getCategoryDailyChange('tw',now);
assert.equal(change.partial,true);assert.equal(change.compared,3);assert.equal(change.count,4);
assert.match(ctx.categoryDailyChangeContent('tw',now).text,/（部分）/);
assert.match(ctx.categoryDailyChangeContent('tw',now).title,/M：無前一日/);
add('us',{id:'u',symbol:'U',shares:2,currentPrice:90},{price:100});
assert.equal(ctx.getCategoryDailyChange('us',now).amount,-640);
assert.match(ctx.categoryDailyChangeContent('us',now).className,/loss/);
add('crypto',{id:'c1',name:'BTCUSDT',quantity:2,currentPrice:110},{price:100});
add('crypto',{id:'c2',name:'ETHUSDT',side:'short',quantity:1,currentPrice:120},{price:100});
change=ctx.getCategoryDailyChange('crypto',now);
assert.equal(change.amount,0);assert.equal(change.basis,9600);assert.equal(change.pct,0);
assert.match(ctx.categoryDailyChangeContent('crypto',now).className,/daily-neutral/);
add('fund',{id:'f1',name:'F',cost:80,currentValue:110},{price:100,cost:80});
add('fund',{id:'f2',name:'G',cost:40,currentValue:45},{price:50,cost:40});
assert.equal(ctx.getCategoryDailyChange('fund',now).amount,5);
assert.ok(Math.abs(ctx.getCategoryDailyChange('fund',now).pct-5/150*100)<1e-10);
state.funds[1].cost=50;
assert.equal(ctx.getCategoryDailyChange('fund',now).partial,true,'fund subscription/cost edits are not daily gains');
assert.equal(ctx.getCategoryDailyChange('fund',now).amount,10);
const total=ctx.getCategoryDailyChange('all',now);
assert.equal(total.amount,-550,'portfolio is the unrounded sum of all four category daily gains');
assert.equal(total.basis,17200);
assert.ok(Math.abs(total.pct-(-550/17200*100))<1e-10,'total % uses combined basis, not an average of sector percentages');
assert.equal(total.count,9);assert.equal(total.compared,7);assert.equal(total.partial,true);
assert.equal(total.missing.length,2);
ctx.renderCategoryDailyChanges(now);
assert.match(nodes[0].textContent,/DPnL.*部分/);assert.match(nodes[1].textContent,/DPnL -\$0.6K -10%/);
assert.equal(nodes[4].textContent,'DPnL -$0.5K -3.2%（部分）');assert.match(nodes[4].className,/loss/);
state.usHoldings[0].currentPrice=120;
ctx.renderCategoryDailyChanges(now);
assert.equal(nodes[1].textContent,'DPnL +$1.2K +20%','price updates recalculate the category label');
assert.match(nodes[1].className,/gain/);
assert.equal(nodes[4].textContent,'DPnL +$1.3K +7.97%（部分）');assert.match(nodes[4].className,/gain/);
const beforeCash=JSON.stringify(ctx.getCategoryDailyChange('all',now));
state.cash=123456789;state.usCashUsd*=2;state.cryptoCashUsdt*=2;
assert.equal(JSON.stringify(ctx.getCategoryDailyChange('all',now)),beforeCash,'cash transfers are not daily gains');
assert.match(source,/function renderSummary\([^]*?renderCategoryDailyChanges\(\);/,'all summary refreshes update category DPnL');
assert.equal(ctx.getCategoryDailyChange('tw',new Date('2026-11-24T02:00:00Z')).available,false,'no older day masquerades as yesterday');
state.usHoldings=[];
assert.equal(ctx.categoryDailyChangeContent('us',now).text,'DPnL —');
state.funds=[];add('fund',{id:'empty',name:'empty',cost:10,currentValue:10});
assert.equal(ctx.categoryDailyChangeContent('fund',now).text,'DPnL —');
assert.equal(ctx.getCategoryDailyChange('fund',now).compared,0);
state.holdings=[];state.cryptoContracts=[];state.funds=[];
assert.equal(ctx.categoryDailyChangeContent('all',now).text,'DPnL —','empty total does not fabricate zero return');
add('tw',{id:'no-yesterday',symbol:'N',shares:1,currentPrice:100});
assert.equal(ctx.categoryDailyChangeContent('all',now).text,'DPnL —','all missing data stays unavailable');
const html=fs.readFileSync(__dirname+'/index.html','utf8'),css=fs.readFileSync(__dirname+'/styles.css','utf8');
assert.equal((html.match(/data-category-daily=/g)||[]).length,5,'four main classification headings plus portfolio total');
assert.match(html,/id="totalValue">[^<]+<\/strong>\s*<small[^>]+data-category-daily="all"/);
assert.match(css,/\.summary-asset-values \{[^}]*flex-wrap: wrap;/);
for(const market of ['tw','us','fund','crypto']) assert.match(html,new RegExp('data-category-total="[^"]+">[^<]+</small><small[^>]+data-category-daily="'+market+'"'));
assert.match(css,/\.category-heading \{[^}]*flex-wrap: wrap;/);
assert.match(source,/function refreshDailyChangeLabels\([^]*?renderCategoryDailyChanges\(\);/);
console.log('PASS: portfolio and four category DPnL, weighted totals, excluded cash flows, shorts, FX, funds, missing data, rollover, live label refresh and wrapping');
